-- Категория «Крепёж и монтаж» в каталоге товаров смущала: слово «монтаж»
-- теперь принадлежит отдельному каталогу монтажных работ. В товарах
-- остаётся только физический крепёж (кронштейны, дюбели, стяжки).
--
-- Переименовываем платформенную категорию mount → «Крепёж». company='NULL'
-- обеспечивает что RLS-политика modify не помешает: мы под ролью
-- smeteora_migrator (BYPASSRLS).

UPDATE product_categories
   SET name = 'Крепёж'
 WHERE company_id IS NULL
   AND source     = 'platform'
   AND code       = 'mount';
